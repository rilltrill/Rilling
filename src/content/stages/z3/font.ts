const ROWS = new Map<string, string[]>();
for (const [k, v] of Object.entries(GLYPHS)) ROWS.set(k, v.split('|'));

/** Width in metres of `text` at pixel size `px` (6 px per glyph incl. spacing). */
export function textWidth(text: string, px: number): number {
  return Math.max(0, text.length * 6 - 1) * px;
}

/**
 * Add `text` centred at (x, y) in the parent's XY plane, facing +Z, `depth` thick.
 * Returns the parent for chaining.
 */
export function addText(
  parent: THREE.Object3D,
  text: string,
  mat: THREE.Material,
  x: number,
  y: number,
  z: number,
  px: number,
  depth = 0.04,
): THREE.Object3D {
  const w = textWidth(text, px);
  let cx = x - w / 2;
  for (const ch of text.toUpperCase()) {
    const rows = ROWS.get(ch) ?? ROWS.get(' ')!;
    for (let r = 0; r < 7; r++) {
      const row = rows[r];
      let c = 0;
      while (c < 5) {
        if (row[c] !== '1') {
          c++;
          continue;
        }
        let e = c;
        while (e < 5 && row[e] === '1') e++;
        const len = e - c;
        Kit.add(parent, Kit.box(len * px, px, depth), mat, cx + (c + len / 2) * px, y + (3 - r) * px, z);
        c = e;
      }
    }
    cx += 6 * px;
  }
  return parent;
}
