/** Width of a string in metres for a given pixel size (5 px glyph + 1 px gap). */
export function textWidth(str: string, px: number): number {
  return Math.max(0, str.length * 6 - 1) * px;
}

/**
 * Add pixel lettering to `parent`. The text is centred on (x, y) in the plane
 * of the group rotated by `ry` (letters face +Z before rotation).
 */
export function pixelText(
  parent: THREE.Object3D,
  str: string,
  material: THREE.Material,
  x: number,
  y: number,
  z: number,
  px: number,
  ry = 0,
  depth = px * 0.6,
): THREE.Group {
  const g = new THREE.Group();
  g.position.set(x, y, z);
  g.rotation.y = ry;
  parent.add(g);
  // (PIXEL WORLD records: painted lettering replaces the block letters.)
  g.userData.pwText = { str, px, color: (material as THREE.MeshBasicMaterial).color.getHex(), glow: (material as THREE.MeshBasicMaterial).isMeshBasicMaterial === true };
  const w = textWidth(str, px);
  const geo = Kit.box(px * 1.02, px * 1.02, depth);
  let cx = -w / 2 + px / 2;
  for (const ch of str.toUpperCase()) {
    const rows = GLYPHS[ch] ?? GLYPHS[' '];
    for (let r = 0; r < 7; r++) {
      const row = rows[r];
      // Merge horizontal runs into single boxes.
      let c = 0;
      while (c < 5) {
        if (row[c] !== '1') {
          c++;
          continue;
        }
        let e = c;
        while (e + 1 < 5 && row[e + 1] === '1') e++;
        const len = e - c + 1;
        const m = new THREE.Mesh(len === 1 ? geo : Kit.box(px * len + px * 0.02, px * 1.02, depth), material);
        m.position.set(cx + ((c + e) / 2) * px, (3 - r) * px, 0);
        g.add(m);
        c = e + 1;
      }
    }
    cx += px * 6;
  }
  return g;
}
